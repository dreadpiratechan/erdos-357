"""Generate lean/Erdos/Proofs/P0357Upper4.lean from a band design (Erdos #357 upper bound, round 4).

Design JSON: {"M": M, "bands": [[l, a, b], ...]}.  Band i is family l with w in (a*j, b*j], and
n' = M*j.  Y-active cells (units of j) are [l a, l b], X-active cells are [(l+1) a, (l+1) b].
Total degree bound D = 2 per cell (Y-only band: 2, X-only band: 1, both: 3).
The script re-checks the design (cell bounds and an exact integer count at several j), then
writes the Lean module.

Usage:  py gen/gen_design4.py design.json out.lean [--module P0357Upper4]
"""
import sys, json
from fractions import Fraction
from math import ceil

J0 = 12          # smallest j for which the cell model is valid (needs j > l + 2 for l <= 9)
D = 2


def breakpoints(bands):
    pts = set()
    for l, a, b in bands:
        pts.update([l * a, l * b + 1, (l + 1) * a, (l + 1) * b + 1])
    return sorted(pts)


def status(l, a, b, lo, hi):
    """Cells [lo, hi) vs the band's Y-range [l a, l b] and X-range [(l+1) a, (l+1) b]."""
    def chk(c0, c1):
        if lo >= c0 and hi <= c1 + 1:
            return 1
        assert hi <= c0 or lo >= c1 + 1, (l, a, b, lo, hi, c0, c1)
        return 0
    return chk(l * a, l * b), chk((l + 1) * a, (l + 1) * b)


def bound_of(y, x):
    return {(0, 0): 0, (1, 0): 2, (0, 1): 1, (1, 1): 3}[(y, x)]


def check_design(bands, M):
    P = breakpoints(bands)
    worst = 0
    for k in range(len(P) - 1):
        s = sum(bound_of(*status(l, a, b, P[k], P[k + 1])) for l, a, b in bands)
        worst = max(worst, s)
        assert s <= D, (k, P[k], P[k + 1], s)
    for l, a, b in bands:
        assert 1 <= l <= J0 - 3
        assert l * a >= M // 2, ("t < l(alpha+1)", l, a)
        assert (l + 1) * b <= 2 * M // 3, ("theta", l, b)
        assert (l + 1) * b * 1 + 0 <= 2 * M // 3
    return worst


def brute(bands, M, j):
    """Exact max over z of sum_i cnt_i(z) at this j (independent of the cell model)."""
    top = (2 * M // 3 + 2) * j + 100
    d = [0] * (top + 3)
    for l, a, b in bands:
        for w in range(a * j + 1, b * j + 1):
            # Hit l w z  (Y-run and X-run are disjoint, so each w contributes once per z)
            d[l * w] += 1
            d[l * w + l + 1] -= 1
            d[(l + 1) * w + 1] += 1
            d[(l + 1) * w + l + 1] -= 1
    cur = 0
    mx = 0
    for z in range(top + 1):
        cur += d[z]
        mx = max(mx, cur)
    return mx


def gen(bands, M):
    S = sum(b - a for l, a, b in bands)
    P = breakpoints(bands)
    t = M // 2
    th = 2 * M // 3
    assert 3 * th == 2 * M and 2 * t == M
    N0 = M * J0
    s_c = 700
    # 3 (2m + s_c + 1)^2 > 4 (m + 1)^2 + 4 (M - 1) + 6 for all m
    assert 3 * (s_c + 1) ** 2 > 4 * (M - 1) + 6 + 4 * 0 + 4
    K1 = (M - S) * M + 2 * M * s_c
    K2 = M + S * N0 + 2 * M
    Kc = max(K1, K2)
    fr = Fraction(M - S, 2 * M)
    Cint = ceil(Fraction(Kc, 2 * M))
    out = []
    A = out.append
    A("import Mathlib")
    A("import Erdos.Proofs.P0357Upper4Gen")
    A("/-! Erdos 357, upper bound, round 4: a %d-band design (GENERATED by problems/0357/gen/gen_design4.py;" % len(bands))
    A("do not edit by hand).")
    A("")
    A("With `n' = %d * j`, `t = %d j`, `θ = %d j + 1`, the bands `(l; a, b)` (family `l`, `w ∈ (a j, b j]`)" % (M, t, th))
    A("  " + ", ".join("(%d; %d, %d)" % (l, a, b) for l, a, b in bands))
    A("have total degree `≤ 2` at every integer (checked cell by cell in `bandsL_fib`), hence")
    A("`%d * j ≤ 2 * #holes`.  Combined with `main_count` this gives" % S)
    A("`%d f(n) ≤ %d n + %d sqrt n + C`, i.e. `f(n) ≤ (%d/%d) n + 2 sqrt n + O(1)`, with" % (2 * M, M - S, 4 * M, fr.numerator, fr.denominator))
    A("`%d/%d = 1/2 - %d/%d`. -/" % (fr.numerator, fr.denominator, S, 2 * M))
    A("namespace Erdos357Upper")
    A("open Finset")
    A("")
    A("/-- The design (in units of `j`). -/")
    A("def bandsL (j : ℕ) : List (ℕ × ℕ × ℕ) :=")
    A("  [" + ",\n   ".join("(%d, %d * j, %d * j)" % (l, a, b) for l, a, b in bands) + "]")
    A("")
    A("theorem bandsL_ok (j : ℕ) (hj : %d ≤ j) :" % J0)
    A("    ∀ p ∈ bandsL j, 1 ≤ p.1 ∧ %d * j < p.1 * (p.2.1 + 1) ∧" % t)
    A("      (p.1 + 1) * p.2.2 + p.1 ≤ %d * j + 1 := by" % th)
    A("  intro p hp")
    A("  simp only [bandsL, List.mem_cons, List.mem_nil_iff, or_false] at hp")
    A("  rcases hp with " + " | ".join(["rfl"] * len(bands)) + " <;>")
    A("    refine ⟨by norm_num, ?_, ?_⟩ <;> dsimp only <;> omega")
    A("")
    A("theorem bandsL_fib (j : ℕ) (hj : %d ≤ j) (z : ℕ) :" % J0)
    A("    ((bandsL j).map (fun p => cnt p.1 p.2.1 p.2.2 z)).sum ≤ %d := by" % D)
    A("  simp only [bandsL, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]")

    def leaf(lo, hi, ind):
        L = []
        for i, (l, a, b) in enumerate(bands):
            y, x = status(l, a, b, lo, hi)
            al = "(%d * j)" % a
            be = "(%d * j)" % b
            if (y, x) == (0, 0):
                L.append("have c%d := cnt_zero %d %s %s z (by omega) (by omega)" % (i, l, al, be))
            elif (y, x) == (1, 0):
                L.append("have c%d := cnt_Y2 %d %s %s z (by norm_num) (by omega)" % (i, l, al, be))
            elif (y, x) == (0, 1):
                L.append("have c%d := cnt_X1 %d %s %s z (by omega)" % (i, l, al, be))
            else:
                L.append("have c%d := cnt_YX3 %d %s %s z (by norm_num)" % (i, l, al, be))
        L.append("omega")
        return [ind + s for s in L]

    for k in range(len(P)):
        A("  rcases lt_or_ge z (%d * j) with h%d | h%d" % (P[k], k, k))
        A("  · -- z below %d j" % P[k])
        if k == 0:
            for i, (l, a, b) in enumerate(bands):
                A("    have c%d := cnt_zero %d (%d * j) (%d * j) z (by omega) (by omega)" % (i, l, a, b))
            A("    omega")
        else:
            out.extend(leaf(P[k - 1], P[k], "    "))
    for i, (l, a, b) in enumerate(bands):
        A("  have c%d := cnt_zero %d (%d * j) (%d * j) z (by omega) (by omega)" % (i, l, a, b))
    A("  omega")
    A("")
    A("/-- The packing count: `%d * j ≤ 2 * #holes` for `n' = %d * j`. -/" % (S, M))
    A("theorem design_count {a : ℕ → ℕ} {k j : ℕ} (H : Adm a k (%d * j)) (hj : %d ≤ j) :" % (M, J0))
    A("    %d * j ≤ 2 * (holes a k (%d * j) (%d * j + 1)).card := by" % (S, t, th))
    A("  have h := list_count H (t := %d * j) (θ := %d * j + 1) (D := %d) (bandsL j)" % (t, th, D))
    A("    (bandsL_ok j hj) (bandsL_fib j hj)")
    A("  have e : ((bandsL j).map (fun p => p.2.2 - p.2.1)).sum = %d * j := by" % S)
    A("    simp only [bandsL, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]")
    A("    omega")
    A("  rw [e] at h")
    A("  exact h")
    A("")
    A("/-- The crossing bound with the design: `%d k ≤ %d (n + %d) + %d sqrt(2θ)`, where" % (2 * M, M - S, M, 2 * M))
    A("`θ = %d j + 1` and `j = ⌈n / %d⌉` (the design is applied to `n' = %d j ≥ n`). -/" % (th, M, M))
    A("theorem adm_bound4 {a : ℕ → ℕ} {k n : ℕ} (H : Adm a k n) (hn : %d ≤ n) :" % N0)
    A("    %d * k ≤ %d * (n + %d) +" % (2 * M, M - S, M))
    A("      %d * Nat.sqrt (2 * (%d * ((n + %d) / %d) + 1)) := by" % (2 * M, th, M - 1, M))
    A("  obtain ⟨j, hj⟩ : ∃ j, j = (n + %d) / %d := ⟨_, rfl⟩" % (M - 1, M))
    A("  rw [← hj]")
    A("  have hj1 : %d ≤ j := by omega" % J0)
    A("  have hj2 : n ≤ %d * j := by omega" % M)
    A("  have hj3 : %d * j ≤ n + %d := by omega" % (M, M - 1))
    A("  have H' := H.mono_n hj2")
    A("  have h1 := main_count H' (t := %d * j) (θ := %d * j + 1) (by omega) (by omega)" % (t, th))
    A("    (by omega) (by omega)")
    A("  have h2 := design_count H' hj1")
    A("  omega")
    A("")
    A("/-- **Upper bound, round 4.**  For the literal upstream `f`:")
    A("`%d f(n) ≤ %d n + %d sqrt n + %d`." % (2 * M, M - S, 4 * M, Kc))
    A("In particular `f(n) ≤ (%d/%d) n + 2 sqrt n + O(1)`. -/" % (fr.numerator, fr.denominator))
    A("theorem f_le_upper4 (n : ℕ) :")
    A("    %d * Erdos357.f n ≤ %d * n + %d * Nat.sqrt n + %d := by" % (2 * M, M - S, 4 * M, Kc))
    A("  have hbound : ∀ k, k ∈ {k : ℕ | ∃ a : Fin k → ℤ,")
    A("      Set.range a ⊆ Set.Icc 1 (n : ℤ) ∧ StrictMono a ∧ Erdos357.HasDistinctSums a} →")
    A("      %d * k ≤ %d * n + %d * Nat.sqrt n + %d := by" % (2 * M, M - S, 4 * M, Kc))
    A("    rintro k ⟨a, hr, hm, ha⟩")
    A("    by_cases hn : %d ≤ n" % N0)
    A("    · obtain ⟨b, hb⟩ := adm_of_int a hr hm ha")
    A("      have h := adm_bound4 hb hn")
    A("      have hs : Nat.sqrt (2 * (%d * ((n + %d) / %d) + 1)) ≤ 2 * Nat.sqrt n + %d := by" % (th, M - 1, M, s_c))
    A("        have h1 := Nat.sqrt_le' (2 * (%d * ((n + %d) / %d) + 1))" % (th, M - 1, M))
    A("        have h2 := Nat.lt_succ_sqrt' n")
    A("        by_contra hcon")
    A("        push_neg at hcon")
    A("        set s := Nat.sqrt (2 * (%d * ((n + %d) / %d) + 1))" % (th, M - 1, M))
    A("        set m := Nat.sqrt n")
    A("        have h3 : 3 * s ^ 2 ≤ 4 * n + %d := by omega" % (4 * (M - 1) + 6))
    A("        have h4 : (2 * m + %d) ^ 2 ≤ s ^ 2 := Nat.pow_le_pow_left (by omega) 2" % (s_c + 1))
    A("        simp only [Nat.succ_eq_add_one] at h2")
    A("        nlinarith")
    A("      have := Nat.mul_le_mul_left %d hs" % (2 * M))
    A("      omega")
    A("    · have h1 := Erdos357.finite_int_length_le_half_add_sqrt a hr hm ha")
    A("      omega")
    A("  have hf : Erdos357.f n ≤ (%d * n + %d * Nat.sqrt n + %d) / %d := by" % (M - S, 4 * M, Kc, 2 * M))
    A("    unfold Erdos357.f")
    A("    apply csSup_le'")
    A("    intro k hk")
    A("    have := hbound k hk")
    A("    exact (Nat.le_div_iff_mul_le (by norm_num)).mpr (by omega)")
    A("  have := (Nat.le_div_iff_mul_le (show 0 < %d by norm_num)).mp hf" % (2 * M))
    A("  omega")
    A("")
    A("/-- Real-valued form: `f(n) ≤ (%d/%d) n + 2 sqrt n + %d`, `%d/%d = 1/2 - %d/%d`. -/" %
      (fr.numerator, fr.denominator, Cint, fr.numerator, fr.denominator, S, 2 * M))
    A("theorem f_le_real4 (n : ℕ) :")
    A("    (Erdos357.f n : ℝ) ≤ (%d / %d) * n + 2 * Real.sqrt n + %d := by" % (fr.numerator, fr.denominator, Cint))
    A("  have h := f_le_upper4 n")
    A("  have hm : (Nat.sqrt n : ℝ) ≤ Real.sqrt n := Real.nat_sqrt_le_real_sqrt")
    A("  have h5 : (%d : ℝ) * (Erdos357.f n : ℝ) ≤ %d * n + %d * (Nat.sqrt n : ℝ) + %d := by" % (2 * M, M - S, 4 * M, Kc))
    A("    exact_mod_cast h")
    A("  nlinarith")
    A("")
    A("end Erdos357Upper")
    A("")
    A("/-- Pin: `Erdos357.f` is verbatim the upstream extremal function (Formal Conjectures")
    A("`ErdosProblems/357.lean`, commit c83a94d): integer-valued `Fin k → ℤ`, range in `Icc 1 n`,")
    A("`StrictMono`, and `HasDistinctSums` over all order-connected index sets. -/")
    A("example (n : ℕ) : Erdos357.f n = sSup {k : ℕ | ∃ a : Fin k → ℤ,")
    A("    Set.range a ⊆ Set.Icc 1 n ∧ StrictMono a ∧ Erdos357.HasDistinctSums a} := rfl")
    return "\n".join(out) + "\n", dict(S=S, M=M, Kc=Kc, Cint=Cint, frac="%d/%d" % (fr.numerator, fr.denominator))


if __name__ == '__main__':
    d = json.load(open(sys.argv[1]))
    M = d['M']
    bands = d['bands']
    w = check_design(bands, M)
    S = sum(b - a for l, a, b in bands)
    print('cell check ok; worst cell bound', w, '; S =', S, '; rho = S/(2M) =', S / (2 * M))
    for j in (J0, J0 + 1, 17, 40):
        print('brute j =', j, 'max total degree', brute(bands, M, j))
    src, info = gen(bands, M)
    open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write(src)
    print(info)
