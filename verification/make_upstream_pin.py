"""Generate verification/generated/UpstreamPin.lean from the vendored upstream statement.

The upstream file (google-deepmind/formal-conjectures, FormalConjectures/ErdosProblems/357.lean)
cannot be imported here: it lives in namespace Erdos357 like our copy, and it depends on the
FormalConjecturesUtil package. Instead this script copies the two upstream definitions
`HasDistinctSums` and `f` VERBATIM (byte for byte, docstrings included) into a separate namespace
`Upstream357`, and states that our `Erdos357.f` and `Erdos357.HasDistinctSums` are definitionally
equal to them (`rfl` / `Iff.rfl`). Lean then checks the pin; nothing is retyped by hand.

Usage (from the package root):  py verification/make_upstream_pin.py
"""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / "generated" / "UpstreamPin.lean"


def block(lines, start_marker):
    """Return the lines of the declaration starting at `start_marker`, with its docstring if any,
    up to the next blank line."""
    i = next(k for k, s in enumerate(lines) if s.startswith(start_marker))
    j = i
    if i > 0 and lines[i - 1].rstrip().endswith("-/"):
        j = i - 1
        while not lines[j].lstrip().startswith("/--"):
            j -= 1
    k = i
    while k < len(lines) and lines[k].strip():
        k += 1
    return lines[j:k]


SOURCES = [
    # (file in upstream/, commit, namespace for the verbatim copy)
    ("FormalConjectures_ErdosProblems_357.lean", None, "Upstream357"),          # vendored copy; commit in COMMIT.txt
    ("FormalConjectures_ErdosProblems_357_at_4b5e5275a2.lean", "4b5e5275a2 (2026-10-15)", "Upstream357b"),
]


def main():
    vendored_commit = (ROOT / "upstream" / "COMMIT.txt").read_text().split()[0]
    out = [
        "import Erdos357",
        "",
        "/-! GENERATED by verification/make_upstream_pin.py. Do not edit.",
        "Each namespace below holds the two definitions `HasDistinctSums` and `f` copied verbatim (docstrings included)",
        "from one upstream copy of FormalConjectures/ErdosProblems/357.lean; the theorems state that our definitions",
        "are definitionally equal to them. -/",
        "",
    ]
    for fname, commit, ns in SOURCES:
        raw = (ROOT / "upstream" / fname).read_bytes()
        lines = raw.decode("utf-8").splitlines()
        hds = block(lines, "def HasDistinctSums")
        fdef = block(lines, "noncomputable def f ")
        sha = hashlib.sha256(raw).hexdigest()
        commit = commit or vendored_commit
        out += [
            f"-- source: upstream/{fname}, formal-conjectures commit {commit}, file sha256 {sha}",
            f"namespace {ns}",
            "",
            *hds,
            "",
            *fdef,
            "",
            f"end {ns}",
            "",
            f"/-- Our `HasDistinctSums` is definitionally the one in {fname}. -/",
            f"theorem pin_hasDistinctSums_{ns} {{ι α : Type*}} [Preorder ι] [AddCommMonoid α] (a : ι → α) :",
            f"    Erdos357.HasDistinctSums a ↔ {ns}.HasDistinctSums a := Iff.rfl",
            "",
            f"/-- Our `f` is definitionally the one in {fname}. -/",
            f"theorem pin_f_{ns} : Erdos357.f = {ns}.f := rfl",
            "",
            f"#print {ns}.f",
            f"#print axioms pin_f_{ns}",
            f"#print axioms pin_hasDistinctSums_{ns}",
            "",
        ]
        print(f"{fname}: sha256 {sha}, commit {commit}, copied {len(hds)} + {len(fdef)} lines into {ns}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes("\n".join(out).encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
